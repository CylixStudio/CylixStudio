export type AlertsLang = "ar" | "en";
export type AlertsTextKey = keyof typeof ALERTS_AR;

/**
 * Untouched default texts (alert messages, simulation text, default snippets)
 * follow the active UI language. Anything the user typed stays exactly as typed,
 * so switching AR/EN never rewrites stored settings.
 */
export function localizeAlertText(lang: AlertsLang, value: string, key: AlertsTextKey): string {
  const ar = ALERTS_AR[key];
  const en = ALERTS_EN[key];
  if (value !== ar && value !== en) return value;
  return lang === "ar" ? ar : en;
}
